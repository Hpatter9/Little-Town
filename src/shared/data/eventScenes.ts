// each, in a box that takes the whole screen). `sceneLine` sets the scene from the town as it is (the hour, the
// season, the weather), and `eventPicture` picks one of the painted backgrounds (data/backdrops.ts, the Craftpix
// parallax packs) for the event by what it is about, else by the land and the season.


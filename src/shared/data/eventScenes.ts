const hash = (s: string) => {
  let h = 2166136261;
  for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619) >>> 0;
  return h;
};

/** The picture for an event: by what it's about, else the land and season. */
export function eventPicture(id: string, words: string, now: SceneNow): BackdropId {
  const theme = themeOf(id, words);
  // (green fields in the snow show the snow; a town scene follows the age)
  const outdoorsGreen = theme === 'fields' || theme === 'plains' || theme === 'forest';
  const pool: readonly BackdropId[] =
    theme === 'town' ? TOWN_BY_ERA[now.era] : theme && !(outdoorsGreen && now.season === 'winter') ? POOLS[theme] : byLand(now);
  return pool[hash(id) % pool.length];
}

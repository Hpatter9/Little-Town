const kindOf = (w: string) => (/storm|thunder/.test(w) ? 'storm' : /snow|blizzard/.test(w) ? 'snow' : /rain|drizzle|shower/.test(w) ? 'rain' : /fog|mist/.test(w) ? 'fog' : 'clear');

/** A sentence setting the scene, from the hour, season and weather (varied by the event, so two in a day differ). */
export function sceneLine(now: SceneNow, salt: number): string {
  const lines = SKY[kindOf(now.weather)][PART(now.hour)];
  return lines[Math.abs(salt) % lines.length].replace('{season}', now.season);
}


/** The town as the event finds it. */
export interface SceneNow {
  hour: number;
  season: Season;
  weather: string;
  biome: Biome;
  era: Era;
  sea: boolean;
}

const PART = (h: number) => (h < 5 ? 'night' : h < 9 ? 'morning' : h < 13 ? 'midday' : h < 17 ? 'afternoon' : h < 21 ? 'evening' : 'night');

